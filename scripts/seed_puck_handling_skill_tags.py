async def seed() -> None:
    async with AsyncSessionLocal() as session:
        exercises_by_name = {
            row.name: row for row in (await session.execute(select(Exercise))).scalars().all()
        }
        skills_by_name = {
            row.name: row for row in (await session.execute(select(Skill))).scalars().all()
        }
        existing_pairs = {
            (row.exercise_id, row.skill_id)
            for row in (await session.execute(select(SkillTag))).scalars().all()
        }

        created = 0
        skipped = 0
        for exercise_name, skill_entries in TAGS:
            exercise = exercises_by_name.get(exercise_name)
            if exercise is None:
                print(f"SKIP (exercise not found): {exercise_name}")
                continue
            for skill_name, transfer_note in skill_entries:
                skill = skills_by_name.get(skill_name)
                if skill is None:
                    print(f"SKIP (skill not found): {skill_name} for {exercise_name}")
                    continue
                if (exercise.id, skill.id) in existing_pairs:
                    skipped += 1
                    continue
                session.add(
                    SkillTag(exercise_id=exercise.id, skill_id=skill.id, transfer_note=transfer_note)
                )
                created += 1
                print(f"OK: {exercise_name} -> {skill_name}")

        await session.commit()
        print(f"\nDone. Created {created}, skipped {skipped} (already tagged).")


if __name__ == "__main__":
    asyncio.run(seed())
