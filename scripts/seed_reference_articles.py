async def seed() -> None:
    async with AsyncSessionLocal() as session:
        existing_titles = set(
            (await session.execute(select(ReferenceArticle.title))).scalars().all()
        )

        created = 0
        for data in ARTICLES:
            if data["title"] in existing_titles:
                continue
            session.add(ReferenceArticle(**data))
            created += 1

        await session.commit()
        print(f"Seeded {created} new article(s), skipped {len(ARTICLES) - created} existing.")


if __name__ == "__main__":
    asyncio.run(seed())
