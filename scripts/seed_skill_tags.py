async def seed() -> None:
    async with AsyncSessionLocal() as session:
        exercise_ids = dict(
            (await session.execute(select(Exercise.name, Exercise.id))).all()
        )
        skill_ids = dict((await session.execute(select(Skill.name, Skill.id))).all())
        existing_pairs = set(
            (await session.execute(select(SkillTag.exercise_id, SkillTag.skill_id))).all()
        )

        created = 0
        skipped_existing = 0
        missing: list[tuple[str, str]] = []

        for exercise_name, skill_name, transfer_note in TAGS:
            exercise_id = exercise_ids.get(exercise_name)
            skill_id = skill_ids.get(skill_name)
            if exercise_id is None or skill_id is None:
                missing.append((exercise_name, skill_name))
                continue
            if (exercise_id, skill_id) in existing_pairs:
                skipped_existing += 1
                continue
            session.add(
                SkillTag(exercise_id=exercise_id, skill_id=skill_id, transfer_note=transfer_note)
            )
            existing_pairs.add((exercise_id, skill_id))
            created += 1

        await session.commit()
        print(f"Created {created} new SkillTag(s), skipped {skipped_existing} existing.")
        if missing:
            print("WARNING: could not resolve these (exercise, skill) pairs:")
            for exercise_name, skill_name in missing:
                print(f"  - {exercise_name!r} / {skill_name!r}")


if __name__ == "__main__":
    asyncio.run(seed())
